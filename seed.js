async function seedUsers() {
  console.log('⏳ กำลังติดตั้งข้อมูลผู้ใช้...');
  for (const sample of sampleUsers) {
    const user = await User.findOne({ username: sample.username });
    if (user) {
      user.fullName = sample.fullName;
      user.role = sample.role;
      user.isActive = true;
      user.password = DEMO_PASSWORD;
      await user.save();
    } else {
      await User.create({ ...sample, password: DEMO_PASSWORD });
    }
  }
  console.log('✅ ติดตั้งผู้ใช้เสร็จสิ้น (4 บัญชี)');
}

async function seedTables() {
  console.log('⏳ กำลังติดตั้งข้อมูลโต๊ะ...');
  for (const sample of sampleTables) {
    await Table.updateOne(
      { tableNumber: sample.tableNumber },
      { $set: sample },
      { upsert: true, runValidators: true }
    );
  }
  console.log(`✅ ติดตั้งโต๊ะเสร็จสิ้น (${sampleTables.length} โต๊ะ)`);
}

async function seedMenus() {
  console.log('⏳ กำลังติดตั้งข้อมูลเมนู (ราคาตามตลาด, สต็อก 150-300, จัดหมวดหมู่แล้ว)...');
  let createdCount = 0;
  for (const sample of sampleMenus) {
    const exists = await Menu.exists({ name: sample.name });
    if (!exists) {
      await Menu.create(sample);
      createdCount += 1;
    }
  }
  console.log(`✅ ติดตั้งเมนูเสร็จสิ้น (เพิ่มใหม่ ${createdCount} รายการ)`);
}

