const MENU_IMAGE_DIR = path.join(__dirname, 'public', 'assets', 'images', 'menu');
const MENU_IMAGE_URL_PREFIX = '/assets/images/menu/';
const DEFAULT_MENU_IMAGE = '/assets/images/default-food.jpg';

// ---------- ตัวช่วยจับคู่ไฟล์รูป ----------
const menuImageFiles = (() => {
  try {
    return fs.readdirSync(MENU_IMAGE_DIR);
  } catch (error) {
    console.warn('Menu image folder could not be read:', error.message);
    return [];
  }
})();

const menuImageFileSet = new Set(menuImageFiles);
const menuImageByBaseName = new Map();
for (const file of menuImageFiles) {
  const baseName = file.replace(/\.[^.]+$/, '').toLowerCase();
  if (!menuImageByBaseName.has(baseName)) menuImageByBaseName.set(baseName, file);
}

function resolveMenuImage(imageFile) {
  const fileName = String(imageFile || '').trim();
  if (!fileName) return { imageUrl: DEFAULT_MENU_IMAGE, imageMissing: true, imageNote: '' };
  if (menuImageFileSet.has(fileName)) {
    return { imageUrl: MENU_IMAGE_URL_PREFIX + fileName, imageMissing: false, imageNote: '' };
  }
  const baseName = fileName.replace(/\.[^.]+$/, '').toLowerCase();
  const alternative = menuImageByBaseName.get(baseName);
  if (alternative) {
    return {
      imageUrl: MENU_IMAGE_URL_PREFIX + alternative,
      imageMissing: false,
      imageNote: fileName,
    };
  }
  return { imageUrl: DEFAULT_MENU_IMAGE, imageMissing: true, imageNote: '' };
}

function getRandomInt(min, max) {
  return Math.floor(Math.random() * (max - min + 1)) + min;
}

// ---------- สร้างรายการเมนู (ดึงหมวดหมู่จากคีย์ของ menuCatalog) ----------
const menuEntriesByName = new Map();
for (const [categoryKey, entries] of Object.entries(menuCatalog)) {
  for (const [name, price, imageFile, description] of entries) {
    const resolved = resolveMenuImage(imageFile);
    const candidate = {
      name,
      price,
      description,
      category: categoryKey,
      ...resolved,
    };
    const existing = menuEntriesByName.get(name);
    if (!existing || (existing.imageMissing && !candidate.imageMissing)) {
      menuEntriesByName.set(name, candidate);
    }
  }
}

const sampleMenus = [...menuEntriesByName.values()].map((entry) => ({
  name: entry.name,
  price: entry.price,
  description: entry.description,
  imageUrl: entry.imageUrl,
  isAvailable: true,
  category: entry.category,
  preparationTime: getRandomInt(5, 15),
  stockQuantity: getRandomInt(150, 300),
  lowStockThreshold: 20,
  maxOrderQuantity: getRandomInt(10, 30),
}));

